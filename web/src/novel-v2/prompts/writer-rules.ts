export const WRITER_SCENE_AND_CHARACTER = `## 场景与人物
- 开场让人物处在具体时间、空间与生活过程里。可以先让读者认识地方、秩序、职业、习惯或关系常态，不必立即抛出任务和冲突。
- 场景可以以行动为中心，也可以以观察、相处、等待、回忆触发、内心游移或情感发酵为中心。安静场景不必强造局势变化，只要它让人物或世界变得更具体，并为后续积累真实重量。
- 背景信息必须经由视角人物此刻接触到的空间、物件、习俗、劳动、传闻或记忆展开，不写百科式设定说明；人物内心可以充分展开，但要保留矛盾、犹疑、联想和自我欺骗，不急着归纳结论。
- 重大结果后允许人物暂不作决定。写出即时反应、身体感受、旧经验牵引和情感余波，但不要替人物总结"这意味着什么"。动作、对白或物件已经传达含义后可以停笔，给读者留出判断空间。
- 情感重场戏可以让人物实际感知到的环境承载情绪，再让人物开口；不规定意象数量，也不强迫每处环境承担线索。不要让概括性心理结论替代人物正在经历的感受。
- 环境描写不得只承担氛围功能。每一处环境意象（天气、灯光、声响、物件状态）必须改变视角人物的判断、引发新的行动、或暴露当下场景的反常——让环境成为视角人物工作的材料，而非背景板。连续使用同类意象（如多次写雪、写灯）时，每次必须呈现可辨识的新信息或新功能。
- 若本章包含重要对决或冲突，必须让它承担底层价值交锋或主题隐喻，而不只为分胜负。打斗即思辨——每一次出剑、折剑、封王都是一次价值表态。
- 人物可以犹豫、误判、自私或顾此失彼。不要为了显得正确而抹平其矛盾，也不要让配角只负责提醒主题；即使戏份少，其行动也应来自自身目标、关系和处境。
- 当本章功能要求主要角色作出取舍时，应让选择、代价及其对后续选项的影响可被读者感知；相处、观察或余波章不必硬造决断。
- 已经由项目或正文建立的标志性器物应参与人物经验、行动或关系；未建立的器物不必为了象征性强行加入。
- 关键瞬间应按其情感和因果重量获得足够篇幅，通过视角人物能感知的动作、停顿、环境变化或他人反应放大，不套固定元素清单。
- 蓝图若安排多个重要角色先后入场，按各自目标、关系和知识边界设计不同的主动行为，不要机械重复同一种介绍或传话方式。蓝图未安排角色亲自到场时，不得为了群像效果强行让其出现。
- 蓝图若安排多角色同场，让他们的行动形成可辨识的协作、回避、误解、信息差或立场张力；安静相处场景可以通过不同关注点和反应积累关系，不强制制造争执。只有当角色各自汇报信息、彼此没有产生任何影响时，才需要重组场景。`;

