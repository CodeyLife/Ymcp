export const WRITER_DIALOGUE_AND_DETAIL = `## 对白与细节
- 重要对白可以来自冲突，也可以来自试探、陪伴、闲谈、礼俗或共同劳动。让主要说话者保持稳定的表达与回避方式，使普通交流也能积累关系和人物质地；删掉只负责转述背景或作者观点的台词。
- 对白不得功能同质化：连续对白回合不得承担同一试探或确认功能（如连续多轮"你是否与X有关"式问答）。每个新回合必须引入新动作、新阻碍或新信息变化，让双方关系由事件推动而非等待对方暴露。
- 潜台词优先于直白宣告：好对白不是"问什么答什么"，而在信息错位与答非所问中让读者自己品。若一句台词直白说出人物情感（如"我舍不得你"），改写为指向具体物件、具体旧事或具体天气的潜台词。每段关键对白最好同时做到三件事——推剧情、立人设、埋钩子，最少占一样；删掉后剧情仍走得动的对白一个字也别留。
- 每个人说话节奏必须可辨识：去掉名字读者仍能认出是谁在说话。依据人物身份、关系和当前目标区分命令、解释、试探、回避与打断方式，给主要角色一个口头禅或小动作作为声音指纹。
- 对白声音指纹：从冻结上下文中的年龄、职业、关系距离、目标、知识边界和既有说话习惯推导每个角色的句长、词汇、直率程度与回避方式，不得套用固定身份模板。交换名字后若对白仍完全成立，检查是否丢失了角色特有的信息边界或关系态度，但不要为了区分而添加上下文中不存在的口癖。
- 角色声部样例：动笔写第一句对白前，先为本章主要说话者各自在内部准备一句说话锚点（词汇、直率程度、回避方式均来自冻结上下文，不得抄进正文）。随后扫描本场景中所有有具体动作呈现（递物、拦阻、指引、反应、整理、呼唤其一）的次要角色，为其中每一人在内部准备一句差异化表达锚点。有动作呈现的次要角色不得全程沉默；仅作背景的群演可不开口。蓝图未安排对白的角色无需强行加戏，独角戏或无对白章节不得人为增加对话。
- 多角色入场方式差异化仅适用于蓝图明确安排角色亲自到场的场景。根据各自当下目标选择观察、询问、操作、等待、回避或协助等不同主动行为；允许角色通过转述、书信、通讯或回忆存在，只要这符合蓝图和叙事视角。
- 动作与神态夹在对白里，少用"说"：连续超过两个"XX 说"时，至少改一处为动作+神态（如"他攥紧拳头，骨节咯吱响：'你骗我。'"）。可用情绪动词：吼、嗤、冷嗤、呢喃、轻叹、低吼、哑声、警告、逼问；以及插入语：顿了顿、抬眼、垂眸、指尖敲了敲桌、脚步顿住。
- 长对白段（超过 6 个回合）必须至少出现一次打断、停顿或跑题之一：打断（"你根本没懂！"）、停顿（空气静了三秒，他才开口）、跑题（明明在吵架，突然问"你吃饭了吗？"）——这三招让对白有呼吸。
- 使用少量只能属于这个人物、职业和地点的细节，并让细节参与行动。通用天气、灯光和景物不能单独承担氛围。
- 禁止训诫式对白：人物不得说出脱离当下情境的一般性道理或职业哲理。改写为指向当下具体的人、关系、目标或风险，让表达带着此刻的试探、自保或权衡，而非像在给读者上课。
- 信息披露对白不能只替作者说明背景。披露重要信息时，应同时体现说话者为何此刻愿意说、接收者如何反应，或这条信息怎样改变双方下一步；日常交流可以只承担陪伴、习惯或关系质地，不必强行制造试探。
- 核心意象只使用项目和正文已经建立的意象。重复出现时呈现可辨识的新状态、关系或功能，不得套用预设的天气、器物或景观，也不要在意象之后补一句解释。`;

