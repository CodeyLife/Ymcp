export const WRITER_BAN_PSYCHOLOGICAL_CONCLUSIONS = `### 1. 禁止作者式心理结论句
不要在行动之后插入替读者总结人物认知或章节意义的句子。以下范式一律删除或改写为行动、感官、对白或环境变化：
- "她第一次知道/她第一次明白/她第一次意识到/她第一次看清/她第一次觉得/她第一次发现……"
- "她忽然懂得/她终于明白/她终于看清/她这才明白……"
- "这意味着/这说明/这代表着/也就是说/换句话说/归根结底/说到底……"
- "不是……而是……""也许……就是……""所谓……不过……"（用作段尾议论时）
- 用"她知道，……"替读者解释人物动机（如"她知道，若现在停下来，脚就再也迈不出去"）
- 用"她知道……也不会/也不能/也无用……"替读者宣告人物无可奈何的结论（如"她知道喊了也不会停"）
- 用"她知道……都会/都将/都逃不掉/都躲不过……"替读者预告人物无法回避的后果（如"她知道此刻出剑，街上所有目光都会落过来"）
- 格言式总结句：在叙事中插入脱离当下场景的哲理概括，如"宫墙里的纸比刀还薄，却比刀留痕""宫里最不值钱的是时间，最值钱的是规矩""有些事不是忘了，是不敢记"。这类句子是作者议论，不是人物体验——删除或改写为人物当下可观察的动作、物件状态或具体反应。
- 隐喻式心理总结句：用意象化比喻替视角人物完成心理判断（如"那些规矩忽然像被人挪动过位置，依旧摆在那里，却有几处对不上了"——表面是规矩意象，实质是作者借比喻宣告人物"秩序感崩塌"的心理结论，仍属于替读者下判断）。这类句子披着意象外衣，但功能仍是作者式心理总结，同样削弱第三人称限知的观察距离。改写路径：让视角人物通过核对具体记录、发现具体异常、采取具体行动呈现"对不上"的过程，由读者自行得出"秩序崩塌"的判断。判定标准——若把比喻句改写为直白陈述（如"规矩对不上了"）后就明显是作者替人物下结论，则该比喻句同样违规。
- 观察否定概括句：用"没有X，没有Y，只是Z"或"不见X，不见Y，唯有Z"的句式把视角人物的观察过程压缩成作者结论。这类句子表面在写人物看到了什么，实质是替人物（和读者）下判断——把可观察的具体对象（装备、阵型、号令、旗帜）压缩成"没有旗帜，没有阵型，只是一群各自赶路的人"，丢失了观察过程，把场景结论喂给读者。改写路径：让视角人物逐项看到具体的可见细节（旗号、队列、物件、动作），由读者从这些细节中自行得出"这不是军队"的判断。判定标准——把句子拆开后，若每一条都是人物可观察的具体对象（如"旗号是青色""队列松散""陶罐缺了口"），则合规；若包含"没有X"的否定判断或"只是/不过/唯有"的概括结论，则违规。
正例：她没有回头。寒露落在发间。（行动与环境承载情绪，不解释）
反例：她第一次知道，离开一座山门，不一定需要有人赶。有时候，是自己先转身。（作者替读者下结论，打破有限第三人称）`;

