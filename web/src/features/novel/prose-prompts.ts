import type { NovelAgentRole } from "./types";

type ProseReviewerRole = Extract<NovelAgentRole, "style-reviewer" | "character-reviewer" | "continuity-reviewer" | "plot-reviewer" | "pacing-reviewer">;

function bulletList(items: string[], empty: string) {
  return items.length ? items.map((item) => `- ${item}`).join("\n") : `- ${empty}`;
}

export function buildChapterDraftPrompt(params: {
  targetWords: number;
  blueprintMarkdown: string;
  contextMarkdown: string;
  mustHappen: string[];
  forbidden: string[];
}) {
  return `只输出一份连续章节正文，不要解释，不要输出标题、代码围栏、指令包装或 Markdown 格式标记。

## 写作优先级
1. 守住已批准事实、人物知识边界、必须发生与禁止事项。
2. 服从本章主导叙事功能与兑现边界，不提前消费后续大纲节点。
3. 让视角人物拥有具体的当下体验；行动、观察、回忆、内心游移、关系相处和情感余波都可以成为正文中心。
4. 最后才考虑意象、辞藻和句式装饰；文采不得压过人物和因果。
发生冲突时严格按以上顺序取舍。

## 硬约束（违反即重写，不得以"润色"名义保留）

### 1. 禁止作者式心理结论句
不要在行动之后插入替读者总结人物认知或章节意义的句子。以下范式一律删除或改写为行动、感官、对白或环境变化：
- "她第一次知道/她第一次明白/她第一次意识到/她第一次看清/她第一次觉得/她第一次发现……"
- "她忽然懂得/她终于明白/她终于看清/她这才明白……"
- "这意味着/这说明/这代表着/也就是说/换句话说/归根结底/说到底……"
- "不是……而是……""也许……就是……""所谓……不过……"（用作段尾议论时）
- 用"她知道，……"替读者解释人物动机（如"她知道，若现在停下来，脚就再也迈不出去"）
- 用"她知道……也不会/也不能/也无用……"替读者宣告人物无可奈何的结论（如"她知道喊了也不会停"）
- 用"她知道……都会/都将/都逃不掉/都躲不过……"替读者预告人物无法回避的后果（如"她知道此刻出剑，街上所有目光都会落过来"）
正例：她没有回头。寒露落在发间。（行动与环境承载情绪，不解释）
反例：她第一次知道，离开一座山门，不一定需要有人赶。有时候，是自己先转身。（作者替读者下结论，打破有限第三人称）

### 2. 禁止对白直接宣告章节主题
对白必须回应当下人物关系、具体冲突或私人情感，不得承担作者对章节主题的总结功能。若一句台词读起来像"作者借角色口宣告立意"，则改写为指向具体人、具体旧事或具体物件的对白，或删除该句。
正例："师弟，你那把剑，我替你磨到出阁那天。"（指向具体人和具体物件）
反例："活着的人，要替死去的人记名字。"（作者借角色口宣告全章主题）

### 3. 短句排比上限（硬约束）
连续 3 句以上单句成段（每句≤10 字且句号收尾）视为短句排比。全章不得超过 2 处，且只能用于极度紧张、决断或生死瞬间的单一节拍。日常叙事、观察、移动、回忆一律用长短句交错，把多个动作熔进一个完整句式。不要用单句成段模仿诗化节奏——这是最典型的机器腔。

## 长篇叙事轴
蓝图规定本章可用的材料与边界，不是待逐项复述的清单。先辨认本章主要承担铺陈、相处、蓄势、行动、余波还是兑现，只围绕这一功能组织正文。主线可以暂不前进，但读者对世界、人物、关系或情感的体验必须有所深化。重大秘密、关系跃迁、伏笔回收和后续大纲节点，除非明确列入“必须发生”，否则只允许留下压力、误读、侧影或未完成的可能性。

## 本章允许兑现且必须发生
${bulletList(params.mustHappen, "无额外硬性节拍")}

## 禁止事项
${bulletList(params.forbidden, "无额外禁止事项")}

## 场景与人物
- 开场让人物处在具体时间、空间与生活过程里。可以先让读者认识地方、秩序、职业、习惯或关系常态，不必立即抛出任务和冲突。
- 场景可以以行动为中心，也可以以观察、相处、等待、回忆触发、内心游移或情感发酵为中心。安静场景不必强造局势变化，只要它让人物或世界变得更具体，并为后续积累真实重量。
- 背景信息必须经由视角人物此刻接触到的空间、物件、习俗、劳动、传闻或记忆展开，不写百科式设定说明；人物内心可以充分展开，但要保留矛盾、犹疑、联想和自我欺骗，不急着归纳结论。
- 重大结果后允许人物暂不作决定。写出即时反应、身体感受、旧经验牵引和情感余波，但不要替人物总结“这意味着什么”。动作、对白或物件已经传达含义后可以停笔，给读者留出判断空间。
- 人物可以犹豫、误判、自私或顾此失彼。不要为了显得正确而抹平其矛盾，也不要让配角只负责提醒主题。

## 对白与细节
- 重要对白可以来自冲突，也可以来自试探、陪伴、闲谈、礼俗或共同劳动。让主要说话者保持稳定的表达与回避方式，使普通交流也能积累关系和人物质地；删掉只负责转述背景或作者观点的台词。
- 对白不得功能同质化：连续对白回合不得承担同一试探或确认功能（如连续多轮"你是否与X有关"式问答）。每个新回合必须引入新动作、新阻碍或新信息变化，让双方关系由事件推动而非等待对方暴露。
- 使用少量只能属于这个人物、职业和地点的细节，并让细节参与行动。通用天气、灯光和景物不能单独承担氛围。
- 核心意象（如寒灯、门人录、雾、江水）全章出现不得超过 3 次，且每次必须呈现可辨识的新状态或新功能（如寒灯从"守着残墙"到"映着剑锋"是状态变化，而"寒灯仍亮着"是静态重复）。不得用同一意象在章尾重复承担与前文相同的象征功能。不要在意象之后补一句解释。

## 节奏与长篇余量
- 叙事段落通常包含 2 至 5 句；不要每句话或每轮对白都另起空行。按动作速度和情绪停顿组织段落，而不是机械切段。
- 章节可以是低强度的铺陈、相处或余波章，不强制设置明显波峰。节奏变化可以来自注意力、距离、关系温度、记忆和意象，而不只来自事件升级。
- 结尾可以停在动作方向、代价、关系裂痕，也可以停在未说出口的话、日常细节、环境变化或情感余韵。不要为了钩子突然引入危险、秘密或第二套事件。

## 篇幅与标点
目标约 ${params.targetWords} 个中文字符。靠行动反应、空间阻力、关系博弈和具体生活细节展开，不得重复事件或增加第二套推进凑篇幅。对白使用中文弯引号，句末标点放在引号内。

## 已批准蓝图
${params.blueprintMarkdown}

## 冻结上下文
${params.contextMarkdown}

输出前静默检查：正文是否让读者在世界、人物、关系、情感或事件中至少深入了一层；是否为了显得有推进而提前兑现了后续材料；若只是把蓝图节点依次写完，先重写为可停留、可感受的场景。`;
}

const REVIEW_FOCUS: Record<ProseReviewerRole, string> = {
  "style-reviewer": "重点检查解释性心理总结、意象替人物说理、可替换的通用细节、段落碎片化、匀速句段和模板化表达。核心意象（寒灯/门人录/雾等）重复出现时是否带来新状态或新功能，而非机械重现同一象征。",
  "character-reviewer": "重点检查人物是否有当下欲望、主动选择和可见代价；对白是否有身份声音与潜台词；配角是否只是作者传声筒。",
  "continuity-reviewer": "重点检查事实、时间、位置、物品、人物知识边界与选择后果是否连续；不要把审美偏好误报为事实矛盾。",
  "plot-reviewer": "重点检查正文是否尊重本章主导功能与兑现边界，是否把大纲压缩成当章任务清单，是否提前完成后续秘密、关系跃迁、重大转折或伏笔回收。铺陈和余波章不要求不可逆结果。",
  "pacing-reviewer": "重点检查章节是否给背景、人物内心、关系和情感留下足够停留，是否急于制造选择、波峰和章尾危险。安静或低强度不等于拖沓；只有内容重复、体验没有深化或失去注意力中心才是节奏问题。仍需识别后半段重复推进和第二个结尾。",
};

export function buildChapterReviewPrompt(params: {
  role: ProseReviewerRole;
  blueprintMarkdown: string;
  numberedDraft: string;
  reviewerContext: string;
}) {
  return `独立审校下面正文。不要读取或猜测写作者解释，只按读者在正文中实际得到的体验评分。

## 评分锚点
- 5：可直接进入生产，只有不影响阅读的微调。
- 4：整体成立，有少量可明确定位的修订。
- 3：结构可读，但机械感、人物能动性、场景或语言存在持续性问题，必须修订。
- 2：明显按蓝图交差、解释多于呈现，或人物与因果不成立。
- 1：无法作为连续小说正文使用。
形式完整、情节都写到了，不等于 4 分以上。若正文像事件报表、心理分析或漂亮句子拼贴，相关维度不得高于 3 分。

## 机械报表识别
检查是否逐条复述蓝图、用“他知道/意识到/这意味着”替读者下结论、让对白传递作者观点、依赖新线索而非人物选择推进、反复用同一意象解释心理、使用可替换的天气与光影、每段承担同样长度和功能。只有形成持续模式才报告，不因单个词机械判错。

## 长篇耐心
先判断本章是在铺陈、相处、蓄势、行动、余波还是兑现。背景展开、人物内省、情感抒发、文学意象和日常过程可以是章节主体，不得因为主线没有明显前进而降分。反过来，若正文过早揭示秘密、完成关系转变、回收伏笔，或把多个后续大纲节点压入本章，应报告为 major。不要建议用突发危险、强行选择或新钩子修复安静章节。

## 当前职责
${REVIEW_FOCUS[params.role]}

每个问题都必须提供正文证据，并填写解决问题实际允许修订的最小 revisionRanges。持续破坏读者体验且需要重写多个段落的问题标为 major；局部润色才标 warning。结构性问题可以填写多个范围，只用于对照的早期段落不得列入修改范围。无法安全定位时返回空数组，不猜测段号。

## 改写示例（major 及以上必填）
对于 severity 为 blocker 或 major 的问题，必须在 rewriteExample 字段中给出具体改写示例。格式：先引用问题原文（可截取关键句），再给出建议改写后的文本。改写应把"替读者下结论"改为"让行动/感官/对白/环境承载"，把"模板表达"改为"只能属于该人物的细节"，把"短句排比"改为"长短句交错"。不要只说"删除该句"——要给出改写后的实际文本，让修订环节可以直接参考。若问题段落需要整段重写，rewriteExample 中给出重写后的完整段落。

plot-reviewer 与 pacing-reviewer 还必须检查正文是否在中后段重新开场、用第二套事件重复已完成的推进，或出现第二个结尾；发现时只标记后出现的重复范围。

## 蓝图
${params.blueprintMarkdown}

## 正文（段落编号仅用于定位）
${params.numberedDraft}

## 相关事实
${params.reviewerContext}`;
}
